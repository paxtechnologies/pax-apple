"""Regenerate the Swift catalog and docs/ERROR_CODES.md from common/pax_errors.py.

  python3 common/gen_error_codes.py          # write both
  python3 common/gen_error_codes.py --check  # exit 1 if either is out of date (CI)
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
sys.path.insert(0, str(HERE))
import pax_errors as pe  # noqa: E402

SWIFT = REPO / "mac-app" / "Sources" / "PaxCore" / "PaxError.swift"
DOCS = REPO / "docs" / "ERROR_CODES.md"
BEGIN = "    // BEGIN GENERATED by common/gen_error_codes.py (do not edit by hand)\n"
END = "    // END GENERATED\n"

AREA_TITLES = {
    "APP": "App", "MAC": "This Mac", "IOS": "iPhone and iPad", "GUARD": "Background protection (pax-guard)",
    "DNS": "Filtering (DNS)", "ESCROW": "Pax server (escrow)", "PROFILE": "Protection settings (profiles)",
    "NET": "Network", "UPDATE": "Updates",
}


def swift_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def swift_block() -> str:
    rows = []
    for c in pe.CODES:
        rows.append(f"        PaxErrorInfo(code: {swift_str(c.code)},\n"
                    f"                     message: {swift_str(c.message)},\n"
                    f"                     action: {swift_str(c.action)},\n"
                    f"                     cause: {swift_str(c.cause)}),\n")
    return BEGIN + "".join(rows) + END


def docs() -> str:
    out = ["<!-- SPDX-License-Identifier: GPL-3.0-only -->",
           "# Pax support error codes",
           "",
           "Every failure a user can hit shows one calm sentence, a **Try again** button and a small code",
           "such as `PAX-GUARD-003`. **Copy details** copies the code, the app version, the macOS (and",
           "iPhone) version and the last 50 log lines, with e-mail addresses, account names, device names",
           "and tokens removed. Nothing about browsing is ever logged.",
           "",
           "Codes are stable: never renumber or reuse one. The source of truth is",
           "`common/pax_errors.py`; this file and `mac-app/Sources/PaxCore/PaxError.swift` are generated",
           "from it by `python3 common/gen_error_codes.py` (CI runs it with `--check`).",
           ""]
    for area in pe.AREAS:
        codes = [c for c in pe.CODES if c.code.split("-")[1] == area]
        if not codes:
            continue
        out += [f"## {area}: {AREA_TITLES[area]}", "",
                "| Code | What the user sees | What to try | Cause (internal) |",
                "|---|---|---|---|"]
        for c in codes:
            cells = [f"`{c.code}`", c.message, c.action, c.cause]
            out.append("| " + " | ".join(x.replace("|", "\\|") for x in cells) + " |")
        out.append("")
    return "\n".join(out)


def render_swift(current: str) -> str:
    start, end = current.index(BEGIN), current.index(END) + len(END)
    return current[:start] + swift_block() + current[end:]


def main() -> int:
    check = "--check" in sys.argv
    swift_new = render_swift(SWIFT.read_text())
    docs_new = docs()
    stale = []
    if SWIFT.read_text() != swift_new:
        stale.append(str(SWIFT))
    if not DOCS.exists() or DOCS.read_text() != docs_new:
        stale.append(str(DOCS))
    if check:
        if stale:
            print("out of date (run python3 common/gen_error_codes.py):", *stale, sep="\n  ")
            return 1
        return 0
    SWIFT.write_text(swift_new)
    DOCS.write_text(docs_new)
    print("wrote", SWIFT, DOCS)
    return 0


if __name__ == "__main__":
    sys.exit(main())
