/// A classified failure: what the UI shows (`info.message`, `info.action`, the code)
/// plus the raw technical text, which only goes into "Copy details".
public struct PaxError: Error, LocalizedError, Equatable {
    public let info: PaxErrorInfo
    public let technical: String

    public init(_ code: String, technical: String = "") {
        self.info = PaxErrorCatalog.info(code)
        self.technical = technical
    }

    public var code: String { info.code }
    public var errorDescription: String? { info.message }

    /// v0.8.1: an exception asked for a site Pax always blocks. Shown straight
    /// away as a plain sentence, with no countdown and nothing to retry.
    public static let restrictedSiteCode = "PAX-DNS-010"
    public var isRestrictedSite: Bool { code == PaxError.restrictedSiteCode }
}

public enum PaxErrorClassifier {
    /// Maps any error Pax can throw to its support code.
    public static func classify(_ error: Error) -> PaxError {
        if let e = error as? PaxError { return e }
        let text = (error as? LocalizedError)?.errorDescription ?? String(describing: error)
        return PaxError(code(for: error, text: text), technical: text)
    }

    static func code(for error: Error, text: String) -> String {
        switch error {
        case let e as MacLockdownError: return code(mac: e, text: text)
        case let e as DeviceServiceError:
            switch e {
            case .toolMissing: return "PAX-IOS-001"
            case .commandFailed(let command, let message):
                if let c = PaxErrorCatalog.code(in: message) { return c }
                return command.contains("make_profile") ? "PAX-PROFILE-001" : "PAX-IOS-002"
            case .unexpectedOutput(let detail):
                return detail.contains("profile") || detail.contains("escrow record") ? "PAX-PROFILE-001" : "PAX-IOS-003"
            case .notSupported: return "PAX-IOS-006"
            case .noDevice: return "PAX-IOS-004"
            }
        case let e as SetupError:
            switch e {
            case .supervisionLost: return "PAX-IOS-008"
            case .supervisionNotConfirmed: return "PAX-IOS-007"
            case .profileNotVerified: return "PAX-PROFILE-003"
            case .keepDataUnavailable: return "PAX-IOS-006"
            case .helperMissing: return "PAX-IOS-005"
            }
        case let e as HelperFailure:
            if let c = PaxErrorCatalog.code(in: e.message) { return c }
            return e.code == "backup_incomplete" ? "PAX-IOS-009" : "PAX-IOS-010"
        case let e as EscrowClient.APIError:
            if e.code == "restricted_site" { return PaxError.restrictedSiteCode }
            // v0.8.5: the server couldn't email the partner, so nothing started (fail closed).
            if e.code == "partner_unreachable" { return "PAX-ESCROW-010" }
            // v0.8.32: this server makes accounts only by an emailed code.
            if e.code == "app_update_required" { return "PAX-ESCROW-020" }
            if e.code == "child_wait_fixed" { return "PAX-ESCROW-021" }   // v0.8.32 child accounts
            if e.code == "child_limit" { return "PAX-ESCROW-022" }
            // v0.8.15: a refused verified support code (one code per reason).
            if let c = VerifiedSupportRelease.apiErrors[e.code] { return c }
            // v0.8.13: pictures and video on X and Bluesky are always blocked.
            if e.code == "media_always_blocked" { return "PAX-DNS-016" }
            return escrowCode(status: e.status, message: e.message)
        case let e as URLError: return networkCode(e)
        case is ServerURLSetting.Problem: return "PAX-NET-004"
        case is PaxDNS.URLError: return "PAX-DNS-001"
        default:
            if (error as NSError).domain == NSURLErrorDomain { return "PAX-NET-001" }
            return PaxErrorCatalog.code(in: text) ?? PaxErrorCatalog.unknownCode
        }
    }

    static func code(mac e: MacLockdownError, text: String) -> String {
        switch e {
        case .preflightFailed(let problems):
            return preflightCode(problems: problems)
        case .wrongPassword: return "PAX-MAC-001"
        case .createAdminFailed: return "PAX-MAC-005"
        case .secureTokenFailed: return "PAX-MAC-006"
        case .verifyAdminFailed: return "PAX-MAC-007"
        case .escrowFailed(let m): return networkCodeIn(m) ?? "PAX-ESCROW-003"
        case .profileInstallFailed(let m): return PaxErrorCatalog.code(in: m) ?? "PAX-PROFILE-002"
        case .guardInstallFailed(let m): return guardCode(m)
        case .demotionFailed: return "PAX-MAC-008"
        case .otherAdminFailed: return "PAX-MAC-003"
        case .stillAdmin: return "PAX-MAC-009"
        case .rolledBack(let step, let why):
            if let c = PaxErrorCatalog.code(in: why) { return c }
            switch step {
            case .installGuard: return guardCode(why)
            case .escrow: return networkCodeIn(why) ?? "PAX-ESCROW-003"
            case .installProfile: return "PAX-PROFILE-002"
            case .demoteOthers: return "PAX-MAC-003"
            default: return "PAX-MAC-010"
            }
        }
    }

    /// pax-guard-install.sh prints a code; older builds don't, so recognise the
    /// launchctl "Bootstrap failed: 5" and quarantine messages too.
    static func guardCode(_ message: String) -> String {
        if let c = PaxErrorCatalog.code(in: message) { return c }
        let m = message.lowercased()
        if m.contains("bootstrap") || m.contains("quarantine") || m.contains("input/output error") {
            return "PAX-GUARD-003"
        }
        if m.contains("command line tools") || m.contains("python3 does not work")
            || m.contains("runtime") { return "PAX-GUARD-002" }
        if m.contains("missing") { return "PAX-GUARD-001" }
        if m.contains("first enforcement") { return "PAX-GUARD-004" }
        if m.contains("not loaded") { return "PAX-GUARD-005" }
        return "PAX-GUARD-006"
    }

    /// Codes for the Mac preflight, in the order MacLockdown checks them.
    public static func preflightCode(problems: [String]) -> String {
        for p in problems {
            if let c = PaxErrorCatalog.code(in: p) { return c }
            if p.contains("isn't the password") { return "PAX-MAC-001" }
            if p.contains("isn't an administrator") { return "PAX-MAC-002" }
            if p.contains("other administrator") { return "PAX-MAC-003" }
            if p.contains("already exists") { return "PAX-MAC-004" }
        }
        return "PAX-MAC-010"
    }

    /// Mirrors escrow_code() in common/pax_errors.py.
    public static func escrowCode(status: Int, message: String = "") -> String {
        switch status {
        case 401: return "PAX-ESCROW-001"
        case 400 where message.contains("wait time"): return "PAX-ESCROW-002"
        case 429: return "PAX-ESCROW-006"
        case 425: return "PAX-ESCROW-007"
        case 500...: return "PAX-ESCROW-004"
        default: return "PAX-ESCROW-005"
        }
    }

    static func networkCode(_ e: URLError) -> String {
        switch e.code {
        case .notConnectedToInternet, .dataNotAllowed, .internationalRoamingOff: return "PAX-NET-002"
        case .secureConnectionFailed, .serverCertificateUntrusted, .serverCertificateHasBadDate,
             .serverCertificateNotYetValid, .serverCertificateHasUnknownRoot, .clientCertificateRejected:
            return "PAX-NET-003"
        case .badURL, .unsupportedURL: return "PAX-NET-004"
        default: return "PAX-NET-001"
        }
    }

    static func networkCodeIn(_ text: String) -> String? {
        if let c = PaxErrorCatalog.code(in: text) { return c }
        let t = text.lowercased()
        if t.contains("offline") || t.contains("not connected to the internet") { return "PAX-NET-002" }
        if t.contains("could not connect") || t.contains("timed out") || t.contains("cannot find host")
            || t.contains("could not be found") { return "PAX-NET-001" }
        return nil
    }
}

/// "Copy details": the code, versions and the last log lines, with personal data
/// removed. Pax never logs browsing, so there is none to remove.
public enum SupportDetails {
    public static let maxLogLines = 50

    public static func text(error: PaxError, appVersion: String, macOSVersion: String,
                            deviceOSVersion: String? = nil, log: [String],
                            redact: [String] = [], date: Date = Date()) -> String {
        var out = [
            "Pax support details",
            "Code: \(error.code)",
            "Message: \(error.info.message)",
            "Cause: \(error.info.cause)",
            "Pax version: \(appVersion)",
            "macOS: \(macOSVersion)",
        ]
        if let ios = deviceOSVersion, !ios.isEmpty { out.append("iPhone/iPad: iOS \(ios)") }
        out.append("Time (UTC): \(ISO8601DateFormatter().string(from: date))")
        if !error.technical.isEmpty {
            out.append("Technical: \(sanitise(error.technical, redact: redact))")
        }
        out.append("Log (last \(min(maxLogLines, log.count)) lines):")
        for line in log.suffix(maxLogLines) { out.append("  " + sanitise(line, redact: redact)) }
        return out.joined(separator: "\n")
    }

    /// Removes e-mail addresses, long tokens/passwords, per-user DNS paths and any
    /// caller-supplied strings (the Mac account name, device names).
    public static func sanitise(_ line: String, redact: [String] = []) -> String {
        var s = line
        let patterns: [(String, String)] = [
            ("[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}", "[email]"),
            ("/u/[A-Za-z0-9_-]+", "/u/[token]"),
            ("(?i)(password|token|secret)([\"'=: ]+)[^\\s\"',]+", "$1$2[redacted]"),
            ("[A-Za-z0-9_-]{24,}", "[redacted]"),
        ]
        for (p, r) in patterns {
            s = s.replacingOccurrences(of: p, with: r, options: .regularExpression)
        }
        for r in redact.sorted(by: { $0.count > $1.count }) where r.count >= 2 {
            s = s.replacingOccurrences(of: r, with: "[redacted]", options: .caseInsensitive)
        }
        return s
    }
