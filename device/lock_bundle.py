#!/usr/bin/env python3
# SPDX-License-Identifier: GPL-3.0-only
"""Write device/requirements-bundle.txt: every pin in requirements-bundle.in with the
sha256 of each file pip may pick for the bundled helper (CPython 3.12 on macOS, arm64,
x86_64 or universal2, plus pure-Python wheels). Hashes come from PyPI's JSON API.

    python3 device/lock_bundle.py [--check]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
IN = HERE / "requirements-bundle.in"
OUT = HERE / "requirements-bundle.txt"
PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s#]+)\s*$")
# CPython 3.12 tags pip accepts: cp312-cp312, cp3x-abi3 (x <= 12), py3/py2.py3-none.
PY_OK = re.compile(r"-(cp312-cp312|cp3(?:[2-9]|1[0-2])-abi3|py3-none|py2\.py3-none)-")
PLAT_OK = re.compile(r"-(any|macosx_\d+_\d+_(?:arm64|x86_64|universal2))\.whl$")


def pins(text: str) -> list[tuple[str, str]]:
    out = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        m = PIN.match(line)
        if not m:
            raise SystemExit(f"not an exact pin: {line!r}")
        out.append((m.group(1).lower(), m.group(2)))
    return out


def wanted(filename: str) -> bool:
    return filename.endswith(".whl") and bool(PY_OK.search(filename)) and bool(PLAT_OK.search(filename))


def render(entries: list[tuple[str, str, list[str]]]) -> str:
    lines = ["# SPDX-License-Identifier: GPL-3.0-only",
             "# GENERATED by device/lock_bundle.py from requirements-bundle.in. Do not edit.",
             "# Installed with: pip install --no-deps --require-hashes --only-binary=:all:", ""]
    for name, version, hashes in entries:
        lines.append(f"{name}=={version} \\")
        lines += [f"    --hash=sha256:{h}" + (" \\" if i < len(hashes) - 1 else "")
                  for i, h in enumerate(hashes)]
    return "\n".join(lines) + "\n"


def fetch(name: str, version: str) -> list[str]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as r:
        files = json.load(r)["urls"]
    hashes = sorted({f["digests"]["sha256"] for f in files if wanted(f["filename"])})
    if not hashes:
        raise SystemExit(f"{name}=={version}: no wheel for CPython 3.12 on macOS")
    return hashes


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the lock is out of date")
    a = ap.parse_args()
    text = render([(n, v, fetch(n, v)) for n, v in pins(IN.read_text())])
    if a.check:
        if OUT.read_text() != text:
            print("device/requirements-bundle.txt is out of date: run device/lock_bundle.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
